/* «Ответошная» — речевая аналитика.
   1) audit(text): проверка ответа по правилам Ильяхова («Пиши, сокращай»): канцелярит, штампы, усилители и оценки,
      отглагольные существительные, страдательный залог, неопределённость, вводные, длинные предложения, повторы.
      Оценка 0–10 (как «Главред»), список замечаний с подсказкой, что сделать.
   2) tidy(text): только безопасные замены, смысл не меняют («выражаем благодарность» → «благодарим»).
   3) analyze(review): разбор отзыва на части — кого и за что благодарят, на что жалуются, есть ли вопрос или просьба,
      сила эмоции, смешанный тон. Разбор идёт в подсказку модели, в выбор вариантов и в карточку. */
