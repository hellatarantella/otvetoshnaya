  var aMemo = {}, aN = 0;
  function audit(text) {
    var k = s(text); if (aMemo[k]) return aMemo[k];
    if (++aN > 3000) { aMemo = {}; aN = 1; }
    return (aMemo[k] = audit0(k));
  }
  function audit0(text) {
    var t = s(text).replace(/^\s*(Здравствуйте|Добрый день)[^\n]*\n?/i, "").replace(/С уважением[^\n]*$/i, "").trim();
    var issues = [], wc = wordsOf(t).length || 1;
    var te = t.replace(/ё/g, "е").replace(/Ё/g, "Е");   // ё и е — одно слово (длина та же, места совпадают)
    RULES.forEach(function (r) {
      var re = new RegExp(r[1].source, r[1].flags), m;
      while ((m = re.exec(te))) issues.push({ type: r[0], word: t.substr(m.index, m[0].length), at: m.index, hint: r[2] });
    });
    sentences(t).forEach(function (x) { var n = wordsOf(x).length; if (n > 25) issues.push({ type: "длинное", word: x.slice(0, 40) + "…", hint: "предложение длиннее 25 слов (" + n + ") — разделите", at: t.indexOf(x) }); });
    var seen = {}, rep = {};
    wordsOf(t).forEach(function (w) { if (w.length < 5 || STOPW.test(w)) return; var k = stem(w); seen[k] = (seen[k] || 0) + 1; if (seen[k] === 3) rep[k] = w; });
    Object.keys(rep).forEach(function (k) { issues.push({ type: "повтор", word: rep[k], hint: "слово повторяется 3 раза и больше — замените или уберите", at: -1 }); });
    var weight = { "канцелярит": 1, "штамп": 1.3, "усилитель": 0.6, "вводное": 0.8, "неопределённость": 0.8, "отглагольное": 0.7, "пассив": 0.9, "длинное": 1, "повтор": 0.6 };
    var pen = issues.reduce(function (a, i) { return a + (weight[i.type] || 1); }, 0);
    var score = Math.max(0, Math.min(10, 10 - pen * 100 / wc / 2));   // как «Главред»: плотность стоп-слов на 100 слов
    issues.sort(function (a, b) { return a.at - b.at; });
    return { score: Math.round(score * 10) / 10, issues: issues, words: wc };
  }
  // keep — фразы сотрудницы (она их дописывает сама): такие не трогаем
  function tidy(text, keep) {
    var t = s(text), K = (keep || []).map(low);
    SAFE.forEach(function (r) { t = t.replace(r[0], function (m) { if (K.some(function (k) { return k.indexOf(low(m)) >= 0; })) return m; return m.replace(new RegExp(r[0].source, r[0].flags.replace("g", "")), r[1]); }); });
    // заглавная буква после замены в начале предложения
    return t.replace(/(^|[.!?]\s+|\n)([а-яё])/g, function (m, a, b) { return a + b.toUpperCase(); });
  }
  function penalty(text) { var a = audit(text); return (10 - a.score) * 0.35; }
  function scoreLine(text) {
    var a = audit(text); if (!s(text).trim()) return "";
    var g = {}; a.issues.forEach(function (i) { g[i.type] = g[i.type] || []; if (g[i.type].indexOf(i.word) < 0) g[i.type].push(i.word); });
    return "Текст: " + String(a.score).replace(".", ",") + " из 10" + (a.issues.length ? " · " + Object.keys(g).map(function (k) { return k + ": «" + g[k].slice(0, 3).join("», «") + "»"; }).join(" · ") : " · чисто");
  }
