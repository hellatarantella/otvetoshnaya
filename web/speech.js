  function sentences(t) { return s(t).replace(/\r/g, "").split(/(?<=[.!?])\s+|\n+/).map(function (x) { return x.trim(); }).filter(Boolean); }
  function wordsOf(t) { return low(t).match(/[а-яa-z0-9-]+/g) || []; }
